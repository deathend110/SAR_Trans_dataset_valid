function outputs = run_generator_confirmation_v2(cfg)
%RUN_GENERATOR_CONFIRMATION_V2 独立确认Range+SFT与扩展BARU+RT生成器。
%
% 仅生成并审计清单：
%   cfg = sarvalid.default_config();
%   cfg.generator_confirmation.dry_run = true;
%   outputs = run_generator_confirmation_v2(cfg);
%
% 完整实验耗时较长；实现授权不等于完整运行授权。

arguments
    cfg (1, 1) struct = sarvalid.default_config()
end

validate_confirmation_config(cfg);
addpath(cfg.repo_root);
gc = cfg.generator_confirmation;
root = gc.output_root;
directories = ["manifests", "stage_c1", "stage_c2", "stage_c3", "stage_c4"];
sarvalid.ensure_dir(root);
for directory = directories
    sarvalid.ensure_dir(fullfile(root, directory));
end

S60 = load(cfg.parameter_file_60);
manifests = sarvalid.build_generator_confirmation_manifests(cfg, S60);
write_manifests(root, manifests);
preregistration = build_preregistration(cfg, manifests);
sarvalid.write_json(fullfile(root, "preregistration.json"), preregistration);
sarvalid.write_json(fullfile(root, "config.json"), cfg);
save(fullfile(root, "config.mat"), "cfg", "S60", "manifests", ...
    "preregistration", "-v7.3");

outputs = struct("cfg", cfg, "manifests", manifests, ...
    "c1", struct(), "c2", struct(), "stage_a", struct(), ...
    "stage_b", struct(), "comparison", table(), ...
    "decision_report", table(), "status", "dry_run");
if gc.dry_run || cfg.runtime.dry_run
    fprintf(['确认实验dry-run完成：development=%d、bridge=%d、' ...
        'confirmation=%d；calibration=%d、evaluation=%d。\n'], ...
        height(manifests.development), height(manifests.bridge_verification), ...
        height(manifests.confirmation), ...
        sum(manifests.sequence.Split == "calibration"), ...
        sum(manifests.sequence.Split == "evaluation"));
    return;
end

c1 = sarvalid.run_generator_confirmation_c1( ...
    cfg, S60, manifests.development);
outputs.c1 = c1;
outputs.status = "C1_complete";
if ~c1.search_closed
    outputs.status = "BARU_search_not_closed";
    write_gate_status(root, outputs.status);
    return;
end
if gc.stop_after == "C1"
    return;
end

c2 = sarvalid.run_generator_confirmation_c2( ...
    cfg, S60, manifests.development, c1);
outputs.c2 = c2;
outputs.status = "C2_complete";
if ~c2.strict_matched
    outputs.status = "difficulty_unmatched_descriptive_only";
    write_gate_status(root, outputs.status);
    return;
end
if gc.stop_after == "C2"
    return;
end

stage_a = sarvalid.run_generator_confirmation_stage_a( ...
    cfg, S60, manifests, c2.locked_generators);
outputs.stage_a = stage_a;
outputs.status = "C3_complete";
if gc.stop_after == "C3"
    return;
end

protocol = struct( ...
    "output_dir", fullfile(root, "stage_c4"), ...
    "resume", gc.resume, "experiment", gc.version, ...
    "signature_context", struct( ...
    "manifest_hashes", manifests.hashes, ...
    "strict_difficulty_tolerance", gc.strict_difficulty_tolerance, ...
    "decision", decision_signature(gc)));
stage_b = sarvalid.run_generator_stage_b( ...
    cfg, S60, manifests.sequence, c2.locked_generators, protocol);
outputs.stage_b = stage_b;
outputs.status = "C4_complete";
if gc.stop_after == "C4"
    return;
end

[comparison, decision_report, scene_summary, ...
    tail_summary, nonzero_fa_summary] = ...
    sarvalid.compare_generator_confirmation(c1, c2, stage_a, stage_b, cfg);
writetable(scene_summary, fullfile(root, "stage_c3", "scene_summary.csv"));
writetable(tail_summary, fullfile(root, "stage_c3", "tail_summary.csv"));
writetable(comparison, fullfile(root, "generator_confirmation_comparison.csv"));
writetable(decision_report, ...
    fullfile(root, "generator_confirmation_decision.csv"));
if ~isempty(nonzero_fa_summary)
    writetable(nonzero_fa_summary, ...
        fullfile(root, "nonzero_fa_summary.csv"));
end
save(fullfile(root, "generator_confirmation_final.mat"), ...
    "cfg", "S60", "manifests", "preregistration", "c1", "c2", ...
    "stage_a", "stage_b", "comparison", "decision_report", ...
    "scene_summary", "tail_summary", "nonzero_fa_summary", "-v7.3");
outputs.comparison = comparison;
outputs.decision_report = decision_report;
outputs.scene_summary = scene_summary;
outputs.tail_summary = tail_summary;
outputs.nonzero_fa_summary = nonzero_fa_summary;
outputs.status = "C5_complete";
write_gate_status(root, outputs.status);
fprintf('生成器独立确认实验完成，最终文件写入%s。\n', root);
end

function validate_confirmation_config(cfg)
required = ["methods", "hl_pairs", "baru_coarse_alpha", ...
    "baru_coarse_As", "baru_fine_offsets", "rt_seed_families", ...
    "baru_alpha_bounds", "baru_As_bounds", ...
    "baru_boundary_gain_tolerance", ...
    "strict_difficulty_tolerance", "tail_noninferiority_margin", ...
    "range_micro_STR_offsets_dB", "range_micro_frequency_offsets", ...
    "nonzero_fa_min", "confirmation_trajectories_per_scene", ...
    "confirmation_samples_per_trajectory", ...
    "confirmation_sample_id_start", "sequence_files_per_scene", ...
    "sequence_id_start", "bootstrap_repetitions", "bootstrap_seed", ...
    "catastrophic_minimum_margin", "mean_noninferiority_margin", ...
    "structure_relative_margin", "seed_spread_fraction", ...
    "overlap_ssim_loss_tolerance", "boundary_jump_db_tolerance", ...
    "output_root", "resume", "dry_run", "stop_after"];
if ~isfield(cfg, "generator_confirmation") || ...
        ~all(isfield(cfg.generator_confirmation, required))
    error('sarvalid:ConfirmationConfigMissing', ...
        'cfg.generator_confirmation缺少必要字段。');
end
gc = cfg.generator_confirmation;
if ~isequal(string(gc.methods), ...
        ["Range_2D_SFT", "BARU_RT", "Range_NonzeroFa_SFT"])
    error('sarvalid:ConfirmationMethodsFixed', ...
        '确认实验的方法集合与预注册协议不一致。');
end
if ~isequal(gc.hl_pairs, [4, 2; 2.5, 1.5])
    error('sarvalid:ConfirmationPairsFixed', ...
        '确认实验固定使用(4,2)与(2.5,1.5)。');
end
expected_seeds = 42 + (0:4) * 1000003;
if cfg.threshold_seed ~= 42 || ...
        ~isequal(gc.rt_seed_families, expected_seeds)
    error('sarvalid:ConfirmationSeedFamilies', ...
        'RT seed family必须遵守42+k×1000003协议。');
end
if strcmpi(char(gc.output_root), char(cfg.output_root)) || ...
        strcmpi(char(gc.output_root), char(cfg.generator_compare.output_root))
    error('sarvalid:ConfirmationOutputIsolation', ...
        '确认实验输出不得与现有results目录重叠。');
end
if ~ismember(string(gc.stop_after), ["C1", "C2", "C3", "C4", "C5"])
    error('sarvalid:ConfirmationStopStage', ...
        'stop_after必须为C1、C2、C3、C4或C5。');
end
if gc.strict_difficulty_tolerance.l_ssim ~= 0.005 || ...
        gc.strict_difficulty_tolerance.delta_ssim ~= 0.01
    error('sarvalid:ConfirmationStrictTolerance', ...
        '确认实验只接受0.005/0.01首轮难度容差。');
end
end

function write_manifests(root, manifests)
writetable(manifests.development, ...
    fullfile(root, "manifests", "development.csv"));
writetable(manifests.bridge_verification, ...
    fullfile(root, "manifests", "bridge_verification.csv"));
writetable(manifests.confirmation, ...
    fullfile(root, "manifests", "confirmation.csv"));
writetable(manifests.sequence, ...
    fullfile(root, "manifests", "sequence.csv"));
writetable(manifests.audit, ...
    fullfile(root, "manifests", "isolation_audit.csv"));
end

function value = build_preregistration(cfg, manifests)
gc = cfg.generator_confirmation;
value = struct( ...
    "material_passport", struct( ...
    "origin_skill", "SAR Master + Experiment Agent", ...
    "origin_mode", "implementation", ...
    "origin_date", "2026-08-15", ...
    "verification_status", "UNVERIFIED", ...
    "version", gc.version), ...
    "manifests", manifests.hashes, ...
    "methods", gc.methods, "hl_pairs", gc.hl_pairs, ...
    "baru_search", struct( ...
    "coarse_alpha", gc.baru_coarse_alpha, ...
    "coarse_As", gc.baru_coarse_As, ...
    "fine_offsets", gc.baru_fine_offsets, ...
    "alpha_bounds", gc.baru_alpha_bounds, ...
    "As_bounds", gc.baru_As_bounds, ...
    "boundary_gain_tolerance", gc.baru_boundary_gain_tolerance), ...
    "range_search", struct( ...
    "strict_difficulty_tolerance", gc.strict_difficulty_tolerance, ...
    "micro_STR_offsets_dB", gc.range_micro_STR_offsets_dB, ...
    "micro_frequency_offsets", gc.range_micro_frequency_offsets, ...
    "nonzero_fa_min", gc.nonzero_fa_min), ...
    "decision", decision_signature(gc), ...
    "seed_families", gc.rt_seed_families, ...
    "normalization", cfg.normalization, "sequence", cfg.sequence);
end

function value = decision_signature(gc)
value = struct( ...
    "mean_noninferiority_margin", gc.mean_noninferiority_margin, ...
    "tail_noninferiority_margin", gc.tail_noninferiority_margin, ...
    "catastrophic_minimum_margin", gc.catastrophic_minimum_margin, ...
    "structure_relative_margin", gc.structure_relative_margin, ...
    "seed_spread_fraction", gc.seed_spread_fraction, ...
    "overlap_ssim_loss_tolerance", gc.overlap_ssim_loss_tolerance, ...
    "boundary_jump_db_tolerance", gc.boundary_jump_db_tolerance, ...
    "stage_a_scene_wins", 6, "stage_b_scene_wins", 7, ...
    "allow_rate_dependent_freeze", false);
end

function write_gate_status(root, status)
sarvalid.write_json(fullfile(root, "gate_status.json"), ...
    struct("status", string(status)));
end
