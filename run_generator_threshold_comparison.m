function outputs = run_generator_threshold_comparison(cfg)
%RUN_GENERATOR_THRESHOLD_COMPARISON 比较Range+2D-SFT与BARU+RT生成器。
%
% 仅检查配置与清单：
%   cfg = sarvalid.default_config();
%   cfg.runtime.dry_run = true;
%   outputs = run_generator_threshold_comparison(cfg);
%
% 默认非dry-run会执行完整Stage A/B，需由用户明确授权后调用。

arguments
    cfg (1, 1) struct = sarvalid.default_config()
end

validate_generator_config(cfg);
addpath(cfg.repo_root);
output_root = cfg.generator_compare.output_root;
sarvalid.ensure_dir(output_root);
sarvalid.ensure_dir(fullfile(output_root, "stage_a"));
sarvalid.ensure_dir(fullfile(output_root, "stage_b"));

S60 = load(cfg.parameter_file_60);
stage_a_manifest = sarvalid.build_stage_a_manifest(cfg, S60);
stage_b_manifest = sarvalid.build_stage_b_manifest(cfg);
writetable(stage_a_manifest, ...
    fullfile(output_root, "stage_a", "stage_a_manifest.csv"));
writetable(stage_b_manifest, ...
    fullfile(output_root, "stage_b", "stage_b_manifest.csv"));
sarvalid.write_json(fullfile(output_root, "config.json"), cfg);
save(fullfile(output_root, "config.mat"), "cfg", "S60", ...
    "stage_a_manifest", "stage_b_manifest");

if cfg.runtime.dry_run
    outputs = struct("cfg", cfg, ...
        "stage_a_manifest", stage_a_manifest, ...
        "stage_b_manifest", stage_b_manifest, ...
        "stage_a", struct(), "stage_b", struct(), ...
        "comparison", table(), "decision_report", table());
    fprintf(['生成器对比dry-run完成：Stage A development=%d、' ...
        'verification=%d；Stage B calibration=%d、evaluation=%d。\n'], ...
        sum(stage_a_manifest.Split == "development"), ...
        sum(stage_a_manifest.Split == "verification"), ...
        sum(stage_b_manifest.Split == "calibration"), ...
        sum(stage_b_manifest.Split == "evaluation"));
    return;
end

stage_a = sarvalid.run_generator_stage_a(cfg, S60, stage_a_manifest);
stage_b = sarvalid.run_generator_stage_b( ...
    cfg, S60, stage_b_manifest, stage_a.locked_generators);
[comparison, decision_report] = sarvalid.compare_generators( ...
    stage_a, stage_b, cfg);
writetable(comparison, fullfile(output_root, ...
    "stage_b", "generator_comparison.csv"));
writetable(decision_report, fullfile(output_root, ...
    "generator_decision_report.csv"));
save(fullfile(output_root, "generator_comparison_final.mat"), ...
    "cfg", "S60", "stage_a_manifest", "stage_b_manifest", ...
    "stage_a", "stage_b", "comparison", "decision_report", "-v7.3");

outputs = struct("cfg", cfg, ...
    "stage_a_manifest", stage_a_manifest, ...
    "stage_b_manifest", stage_b_manifest, ...
    "stage_a", stage_a, "stage_b", stage_b, ...
    "comparison", comparison, "decision_report", decision_report);
end

function validate_generator_config(cfg)
required = ["methods", "hl_pairs", "baru_alpha", "baru_As", ...
    "rt_seed_families", "difficulty_tolerance", "output_root", "resume"];
if ~isfield(cfg, "generator_compare") || ...
        ~all(isfield(cfg.generator_compare, required))
    error('sarvalid:GeneratorConfigMissing', ...
        'cfg.generator_compare缺少必要字段。');
end
if ~isequal(string(cfg.generator_compare.methods), ...
        ["Range_2D_SFT", "BARU_RT"])
    error('sarvalid:GeneratorMethodsFixed', ...
        '本实验固定比较Range_2D_SFT与BARU_RT。');
end
if ~isequal(cfg.generator_compare.hl_pairs, [4, 2; 2.5, 1.5])
    error('sarvalid:GeneratorPairsFixed', ...
        '本实验固定使用(4,2)与(2.5,1.5)倍率对。');
end
expected_seeds = 42 + (0:4) * 1000003;
if cfg.threshold_seed ~= 42 || ...
        ~isequal(cfg.generator_compare.rt_seed_families, expected_seeds)
    error('sarvalid:GeneratorSeedFamilies', ...
        'RT seed family必须遵守42+k×1000003协议。');
end
if strcmpi(char(cfg.generator_compare.output_root), char(cfg.output_root))
    error('sarvalid:GeneratorOutputIsolation', ...
        '生成器对比输出不得与现有results目录相同。');
end
if cfg.stage_a.development_samples_per_scene ~= 2 || ...
        cfg.stage_a.verification_samples_per_scene ~= 10 || ...
        cfg.stage_b.calibration_sequences_per_scene ~= 1 || ...
        cfg.stage_b.sequences_per_scene ~= 3
    error('sarvalid:GeneratorManifestProtocol', ...
        '生成器对比固定使用14/70样本和7/14序列协议。');
end
end
