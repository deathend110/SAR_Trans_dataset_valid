function outputs = run_generator_confirmation_stage_a( ...
        cfg, S60, manifests, locked_generators)
%RUN_GENERATOR_CONFIRMATION_STAGE_A 执行旧验证桥接和新样本盲测。

root = cfg.generator_confirmation.output_root;
bridge_dir = fullfile(root, "stage_c2", "bridge_checkpoints");
confirmation_dir = fullfile(root, "stage_c3");
sarvalid.ensure_dir(bridge_dir);
sarvalid.ensure_dir(confirmation_dir);

bridge_seed_detail = table();
bridge_sample_detail = table();
bridge_summary = table();
confirmation_seed_detail = table();
confirmation_sample_detail = table();
confirmation_summary = table();

for lock_idx = 1:numel(locked_generators)
    lock = locked_generators{lock_idx};
    [seed_rows, sample_rows, summary_row] = ...
        sarvalid.verify_generator_lock( ...
        manifests.bridge_verification, S60, lock, cfg, ...
        bridge_dir, "bridge_verification");
    bridge_seed_detail = append_table(bridge_seed_detail, seed_rows);
    bridge_sample_detail = append_table(bridge_sample_detail, sample_rows);
    bridge_summary = append_table(bridge_summary, summary_row);

    [seed_rows, sample_rows, summary_row] = ...
        sarvalid.verify_generator_lock( ...
        manifests.confirmation, S60, lock, cfg, ...
        confirmation_dir, "confirmation");
    confirmation_seed_detail = append_table( ...
        confirmation_seed_detail, seed_rows);
    confirmation_sample_detail = append_table( ...
        confirmation_sample_detail, sample_rows);
    confirmation_summary = append_table(confirmation_summary, summary_row);
end

scene_summary = table();
tail_summary = table();
for pair_idx = 1:size(cfg.generator_confirmation.hl_pairs, 1)
    q_high = cfg.generator_confirmation.hl_pairs(pair_idx, 1);
    q_low = cfg.generator_confirmation.hl_pairs(pair_idx, 2);
    range = confirmation_sample_detail( ...
        confirmation_sample_detail.QHigh == q_high & ...
        confirmation_sample_detail.QLow == q_low & ...
        confirmation_sample_detail.Method == "Range_2D_SFT", :);
    baru = confirmation_sample_detail( ...
        confirmation_sample_detail.QHigh == q_high & ...
        confirmation_sample_detail.QLow == q_low & ...
        confirmation_sample_detail.Method == "BARU_RT", :);
    [scene_rows, ~, tail_rows] = ...
        sarvalid.summarize_confirmation_samples( ...
        range, baru, q_high, q_low, ...
        cfg.generator_confirmation.tail_noninferiority_margin);
    scene_summary = append_table(scene_summary, scene_rows);
    tail_summary = append_table(tail_summary, tail_rows);
end

writetable(bridge_seed_detail, ...
    fullfile(root, "stage_c2", "bridge_detail.csv"));
writetable(bridge_sample_detail, ...
    fullfile(root, "stage_c2", "bridge_sample_aggregate.csv"));
writetable(bridge_summary, ...
    fullfile(root, "stage_c2", "bridge_summary.csv"));
writetable(confirmation_seed_detail, ...
    fullfile(confirmation_dir, "confirmation_detail.csv"));
writetable(confirmation_sample_detail, ...
    fullfile(confirmation_dir, "confirmation_sample_aggregate.csv"));
writetable(confirmation_summary, ...
    fullfile(confirmation_dir, "confirmation_summary.csv"));
writetable(scene_summary, fullfile(confirmation_dir, "scene_summary.csv"));
writetable(tail_summary, fullfile(confirmation_dir, "tail_summary.csv"));
save(fullfile(confirmation_dir, "stage_c3_final.mat"), ...
    "bridge_seed_detail", "bridge_sample_detail", "bridge_summary", ...
    "confirmation_seed_detail", "confirmation_sample_detail", ...
    "confirmation_summary", "scene_summary", "tail_summary", "-v7.3");

outputs = struct("bridge_seed_detail", bridge_seed_detail, ...
    "bridge_sample_detail", bridge_sample_detail, ...
    "bridge_summary", bridge_summary, ...
    "confirmation_seed_detail", confirmation_seed_detail, ...
    "confirmation_sample_detail", confirmation_sample_detail, ...
    "confirmation_summary", confirmation_summary, ...
    "scene_summary", scene_summary, "tail_summary", tail_summary);
end

function output = append_table(input, rows)
if isempty(input)
    output = rows;
else
    output = [input; rows];
end
end
