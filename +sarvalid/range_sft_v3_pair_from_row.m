function pair = range_sft_v3_pair_from_row(cfg, row)
%RANGE_SFT_V3_PAIR_FROM_ROW 将V3候选表的一行还原为H/L共享参数配置。

threshold = struct("As", cfg.threshold.As, ...
    "STR_dB", double(row.STRdB), ...
    "fr_over_Br", double(row.FrOverBr), ...
    "fa_over_Ba", double(row.FaOverBa), ...
    "phi0", cfg.threshold.phi0);
pair = sarvalid.make_pair_config(cfg, "Range_2D_SFT", ...
    double(row.QHigh), double(row.QLow), 1, threshold);
% 使用包含全部SFT参数和固定seed的稳定键，避免候选结果互相覆盖。
pair.file_key = sarvalid.generator_file_key(pair, cfg.threshold_seed);
if ismember("PairKey", string(row.Properties.VariableNames)) && ...
        string(row.PairKey) ~= string(pair.file_key)
    error('sarvalid:V3CandidateKeyMismatch', ...
        '候选表FileKey与参数重建结果不一致。');
end
end
