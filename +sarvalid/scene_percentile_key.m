function key = scene_percentile_key(scene_name)
%SCENE_PERCENTILE_KEY 将场景全名映射为稳定的MAT文件名键。

scene_name = string(scene_name);
known_names = [ ...
    "SAR_Dataset_Bangkok_1", ...
    "SAR_Dataset_city1_histeq", ...
    "SAR_Dataset_city2_histeq", ...
    "SAR_Dataset_SAR_figure", ...
    "SAR_Dataset_filed", ...
    "SAR_Dataset_port", ...
    "SAR_Dataset_suburb"];
known_keys = [ ...
    "bangkok", ...
    "city1_histeq", ...
    "city2_histeq", ...
    "sar_figure", ...
    "filed", ...
    "port", ...
    "suburb"];

index = find(strcmpi(scene_name, known_names), 1);
if ~isempty(index)
    key = known_keys(index);
    return;
end

key = lower(regexprep(scene_name, '^SAR_Dataset_', ''));
key = regexprep(key, '[^a-z0-9_]+', '_');
key = strip(key, '_');
if strlength(key) == 0
    error('sarvalid:InvalidScenePercentileKey', ...
        '场景名称无法转换为稳定文件键：%s', scene_name);
end
end
