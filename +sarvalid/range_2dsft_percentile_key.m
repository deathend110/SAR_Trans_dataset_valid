function key = range_2dsft_percentile_key(parameters, protocol)
%RANGE_2DSFT_PERCENTILE_KEY 构造包含统计协议的稳定参数键。

required_parameters = [ ...
    "QHigh", "QLow", "STRdB", "FrOverBr", "FaOverBa", "Phi0"];
required_protocol = [ ...
    "low_percentile", "high_percentile", "roi_size", "energy_buffer"];
if ~all(isfield(parameters, required_parameters)) || ...
        ~all(isfield(protocol, required_protocol))
    error('sarvalid:RangeSFTPercentileKeySchema', ...
        '参数或统计协议缺少构造唯一键所需字段。');
end

key = "range_2d_sft" + ...
    "_qh" + encode(parameters.QHigh) + ...
    "_ql" + encode(parameters.QLow) + ...
    "_s" + encode(parameters.STRdB) + ...
    "_fr" + encode(parameters.FrOverBr) + ...
    "_fa" + encode(parameters.FaOverBa) + ...
    "_phi" + encode(parameters.Phi0) + ...
    "_lp" + encode(protocol.low_percentile) + ...
    "_hp" + encode(protocol.high_percentile) + ...
    "_roi" + encode(protocol.roi_size) + ...
    "_eb" + encode(protocol.energy_buffer);
end

function value = encode(number)
value = string(sprintf('%.12g', double(number)));
value = replace(value, "-", "m");
value = replace(value, ".", "p");
value = replace(value, "+", "");
end
